void mat3_mul(const f32 a[3][3], const f32 b[3][3], f32 out[3][3]) {
    f32 p000 = a[0][0] * b[0][0];
    f32 p010 = a[0][1] * b[1][0];
    f32 p020 = a[0][2] * b[2][0];
    f32 p100 = a[1][0] * b[0][0];
    f32 p110 = a[1][1] * b[1][0];
    f32 p120 = a[1][2] * b[2][0];
    f32 p200 = a[2][0] * b[0][0];
    f32 p210 = a[2][1] * b[1][0];
    f32 p220 = a[2][2] * b[2][0];
    f32 p001 = a[0][0] * b[0][1];
    f32 p011 = a[0][1] * b[1][1];
    f32 p021 = a[0][2] * b[2][1];
    f32 p101 = a[1][0] * b[0][1];
    f32 p111 = a[1][1] * b[1][1];
    f32 p121 = a[1][2] * b[2][1];
    f32 p201 = a[2][0] * b[0][1];
    f32 p211 = a[2][1] * b[1][1];
    f32 p221 = a[2][2] * b[2][1];
    f32 p002 = a[0][0] * b[0][2];
    f32 p012 = a[0][1] * b[1][2];
    f32 p022 = a[0][2] * b[2][2];
    f32 p102 = a[1][0] * b[0][2];
    f32 p112 = a[1][1] * b[1][2];
    f32 p122 = a[1][2] * b[2][2];
    f32 p202 = a[2][0] * b[0][2];
    f32 p212 = a[2][1] * b[1][2];
    f32 p222 = a[2][2] * b[2][2];
    f32 m00 = (p000 + p010) + p020;
    f32 m10 = (p100 + p110) + p120;
    f32 m20 = (p200 + p210) + p220;
    f32 m01 = (p001 + p011) + p021;
    f32 m11 = (p101 + p111) + p121;
    f32 m21 = (p201 + p211) + p221;
    f32 m02 = (p002 + p012) + p022;
    f32 m12 = (p102 + p112) + p122;
    f32 m22 = (p202 + p212) + p222;
    out[0][0] = m00;
    out[1][0] = m10;
    out[2][0] = m20;
    out[0][1] = m01;
    out[1][1] = m11;
    out[2][1] = m21;
    out[0][2] = m02;
    out[1][2] = m12;
    out[2][2] = m22;
}
