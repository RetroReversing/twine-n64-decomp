// Multiplies two 3x3 float matrices: out = lhs * rhs.
void mat3_mul(const f32 lhs[3][3], const f32 rhs[3][3], f32 out[3][3]) {
    f32 p000 = lhs[0][0] * rhs[0][0];
    f32 p010 = lhs[0][1] * rhs[1][0];
    f32 p020 = lhs[0][2] * rhs[2][0];
    f32 p100 = lhs[1][0] * rhs[0][0];
    f32 p110 = lhs[1][1] * rhs[1][0];
    f32 p120 = lhs[1][2] * rhs[2][0];
    f32 p200 = lhs[2][0] * rhs[0][0];
    f32 p210 = lhs[2][1] * rhs[1][0];
    f32 p220 = lhs[2][2] * rhs[2][0];
    f32 p001 = lhs[0][0] * rhs[0][1];
    f32 p011 = lhs[0][1] * rhs[1][1];
    f32 p021 = lhs[0][2] * rhs[2][1];
    f32 p101 = lhs[1][0] * rhs[0][1];
    f32 p111 = lhs[1][1] * rhs[1][1];
    f32 p121 = lhs[1][2] * rhs[2][1];
    f32 p201 = lhs[2][0] * rhs[0][1];
    f32 p211 = lhs[2][1] * rhs[1][1];
    f32 p221 = lhs[2][2] * rhs[2][1];
    f32 p002 = lhs[0][0] * rhs[0][2];
    f32 p012 = lhs[0][1] * rhs[1][2];
    f32 p022 = lhs[0][2] * rhs[2][2];
    f32 p102 = lhs[1][0] * rhs[0][2];
    f32 p112 = lhs[1][1] * rhs[1][2];
    f32 p122 = lhs[1][2] * rhs[2][2];
    f32 p202 = lhs[2][0] * rhs[0][2];
    f32 p212 = lhs[2][1] * rhs[1][2];
    f32 p222 = lhs[2][2] * rhs[2][2];
    f32 m00 = (p000 + p010) + p020;
    f32 m10 = (p100 + p110) + p120;
    f32 m20 = (p200 + p210) + p220;
    f32 m01 = (p001 + p011) + p021;
    f32 m11 = (p101 + p111) + p121;
    f32 m21 = (p201 + p211) + p221;
    f32 m02 = (p002 + p012) + p022;
    f32 m12 = (p102 + p112) + p122;
    f32 m22 = (p202 + p212) + p222;
    out[0][0] = m00;
    out[1][0] = m10;
    out[2][0] = m20;
    out[0][1] = m01;
    out[1][1] = m11;
    out[2][1] = m21;
    out[0][2] = m02;
    out[1][2] = m12;
    out[2][2] = m22;
}
