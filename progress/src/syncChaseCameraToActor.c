typedef struct {
    u8 pad0[0x11a8];
    s32 remaining;
    u8 pad1[0x28];
    u32 progress;
    u32 total;
    u8 pad2;
    s8 state;
} Record9D94C;
u32 advanceDataBankPlayback(Record9D94C *record, u32 step) {
    s32 remaining;
    u32 progress, available, amount;
    if (record->state != 3)
        return 0;
    remaining = record->remaining;
    if (remaining > 0) {
        remaining -= step;
        record->remaining = remaining;
        if (remaining <= 0) {
            record->state = 4;
            record->remaining = 0;
        }
    }
    progress = record->progress;
    available = record->total - progress;
    amount = step < available ? step : available;
    record->progress = progress + amount;
    return amount;
}
